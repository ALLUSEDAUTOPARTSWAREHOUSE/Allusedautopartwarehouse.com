const { test } = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')

const read = (path) => readFileSync(path, 'utf8')

test('product-page quote CTA carries product name and canonical page into the quote form', () => {
  const actions = read('components/products/product-card-actions.tsx')
  const quotePage = read('app/quote/page.tsx')
  const route = read('app/api/quote/route.ts')
  assert.match(actions, /productName,/)
  assert.match(actions, /productUrl: detailsHref/)
  assert.match(quotePage, /setProductOfInterest\(name\)/)
  assert.match(quotePage, /productName: productOfInterest/)
  assert.match(quotePage, /productUrl,/)
  assert.match(route, /productName: d\.productName/)
  assert.match(route, /productUrl: d\.productUrl/)
})

test('product links persist without overwriting existing quote/customer data', () => {
  const followup = read('lib/followup.ts')
  const health = read('lib/admin-health.ts')
  assert.match(followup, /ADD COLUMN IF NOT EXISTS product_name text/)
  assert.match(followup, /ADD COLUMN IF NOT EXISTS product_url text/)
  assert.match(followup, /product_name, product_url/)
  assert.match(followup, /input\.productName \|\| null/)
  assert.match(followup, /input\.productUrl \|\| null/)
  assert.match(health, /ADD COLUMN IF NOT EXISTS product_name text/)
  assert.match(health, /ADD COLUMN IF NOT EXISTS product_url text/)
  assert.doesNotMatch(health.slice(health.indexOf('const REPAIR_SQL'), health.indexOf('export async function repairDatabase')), /DROP TABLE|DELETE FROM public\.(leads|orders)/i)
})

test('sales and quote dashboards display linked product and one-click missing-price editor', () => {
  const sales = read('app/admin/sales/page.tsx')
  const quotes = read('app/admin/quotes/page.tsx')
  const card = read('components/admin/quote-lead-card.tsx')
  const productInfo = read('lib/quote-product-info.ts')
  assert.match(sales, /Related product \/ catalog price/)
  assert.match(sales, /Missing price — set it now/)
  assert.match(quotes, /getQuoteProductInfo/)
  assert.match(card, /Product of interest/)
  assert.match(card, /Missing catalog price — set it now/)
  assert.match(productInfo, /effective\.price === null \|\| effective\.price <= 0/)
  assert.match(productInfo, /\/admin\/products\?brand=/)
  assert.match(productInfo, /issue=no_price/)
})

test('only active sales/support roster members receive operations email; owner inbox remains fallback/copy', () => {
  const notify = read('lib/followup-notify.ts')
  assert.match(notify, /WHERE status = 'active' AND role IN \('sales_agent', 'support_team'\)/)
  assert.match(notify, /STAFF_EMAIL\.toLowerCase\(\)/)
  assert.match(notify, /sendToOperations\(/)
  assert.match(notify, /Promise\.all\(recipients\.map/)
  assert.match(notify, /sendCustomerQuoteAcknowledgement/)
  assert.match(notify, /customerEmailReady/)
})

test('customer quote and order forms show provider acceptance rather than promising delivery', () => {
  const quoteForm = read('app/quote/page.tsx')
  const orderRoute = read('app/api/orders/route.ts')
  const checkout = read('app/checkout/page.tsx')
  const stripe = read('lib/stripe-checkout.ts')
  assert.match(quoteForm, /customerConfirmationAccepted/)
  assert.match(orderRoute, /customerConfirmationAccepted: customerNotice\.ok/)
  assert.match(checkout, /email service accepted a confirmation/i)
  assert.match(checkout, /email service did not accept the confirmation email/i)
  assert.match(stripe, /customerConfirmationAccepted: customerNotice\.ok/)
})

test('assignment options are admin-authenticated, sales/support-only and notify the selected owner', () => {
  const actions = read('app/admin/followup-actions.ts')
  const assignments = read('lib/followup-assignments.ts')
  const picker = read('components/admin/followup-assignment-select.tsx')
  assert.match(actions, /const session = await getAdminSession\(\)/)
  assert.match(actions, /setFollowupAssignment\(/)
  assert.match(actions, /notifyFollowupAssignment\(/)
  assert.match(assignments, /status = 'active' AND role IN \('sales_agent', 'support_team'\)/)
  assert.match(picker, /Unassigned/)
  assert.match(picker, /Save assignment/)
})
