const { test } = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')

const read = (path) => readFileSync(path, 'utf8')

test('checkout customers land in the sales portal with order and invoice links', () => {
  const salesPage = read('app/staff/sales/page.tsx')
  const workspace = read('components/staff/sales-workspace.tsx')
  assert.match(salesPage, /listCustomers/)
  assert.match(salesPage, /listOrders/)
  assert.match(salesPage, /listQuoteLeads/)
  assert.match(workspace, /Every checkout customer lands here/)
  assert.match(workspace, /Open branded invoice/)
  assert.match(workspace, /Awaiting email verification/)
  assert.match(workspace, /Email verified/)
})

test('orders require email verification and say they process after payment confirmation', () => {
  const orders = read('app/api/orders/route.ts')
  const notify = read('lib/followup-notify.ts')
  const invoice = read('lib/invoice.ts')
  const verify = read('app/orders/verify/page.tsx')
  const checkout = read('app/checkout/page.tsx')
  assert.match(orders, /sendCustomerOrderVerification/)
  assert.match(notify, /sendCustomerOrderVerification/)
  assert.match(invoice, /Verify email &amp; confirm order/)
  assert.match(invoice, /Your order will be processed after payment confirmation/)
  assert.match(verify, /verifyOrderEmail/)
  assert.match(verify, /Your order will be processed after payment confirmation/)
  assert.match(checkout, /processed after payment confirmation/)
})

test('branded invoices include AUAPW logo, product page links, brand images and cloned terms', () => {
  const invoice = read('lib/invoice.ts')
  const page = read('app/invoice/[orderNumber]/page.tsx')
  const ui = read('components/invoice/order-invoice.tsx')
  const health = read('lib/admin-health.ts')
  const followup = read('lib/followup.ts')
  assert.match(invoice, /AUAPW LLC/)
  assert.match(invoice, /auapw-logo\.png/)
  assert.match(invoice, /productHref/)
  assert.match(invoice, /brandLogoPath/)
  assert.match(invoice, /25% handling and restocking fee/)
  assert.match(invoice, /90-day limited parts warranty/)
  assert.match(page, /getOrderByInvoiceToken/)
  assert.match(ui, /Notes \/ Terms/)
  assert.match(ui, /product page/)
  assert.match(followup, /ADD COLUMN IF NOT EXISTS email_verify_token text/)
  assert.match(followup, /ADD COLUMN IF NOT EXISTS invoice_token text/)
  assert.match(health, /ADD COLUMN IF NOT EXISTS invoice_token text/)
})
