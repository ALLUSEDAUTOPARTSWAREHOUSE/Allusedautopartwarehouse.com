const { test } = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const read = path => readFileSync(path, 'utf8')
test('dedicated uploads page remains admin protected and excludes product rows', () => {
 const page = read('app/admin/uploads/page.tsx')
 assert.match(page, /getAdminSession/)
 assert.match(page, /redirect\('\/admin\/login'\)/)
 assert.match(page, /LargeCatalogUpload brands=\{brands\}/)
 assert.match(page, /UploadSheetForm brands=\{brands\}/)
 assert.doesNotMatch(page, /listManualProducts|ManualProductRow|CatalogSyncPanel/)
 assert.match(page, /BRAND_DIRECTORY.find/)
})
test('sidebar and brand upload shortcuts target separate workspace', () => {
 assert.match(read('components/admin/admin-sidebar.tsx'), /href: '\/admin\/uploads'/)
 assert.match(read('app/admin/products/page.tsx'), /\/admin\/uploads\?brand=/)
 assert.match(read('components/admin/catalog-command-center.tsx'), /href: '\/admin\/uploads'/)
})
